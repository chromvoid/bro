import { describe, expect, it, vi } from 'vitest'
import marks from '@/assets/bro/moods.json'
import { MERGE_MS } from '@/components/brandMood'
import index from '../../index.html?raw'
import { finishBoot, LEAVE_MS, leaveBoot, SMILE_MS } from './boot'

// Only the generated block: parsing the whole page would make the test DOM fetch its styles.
const mark = index.slice(
  index.indexOf('<!-- BEGIN GENERATED BOOT MARK -->'),
  index.indexOf('<!-- END GENERATED BOOT MARK -->'),
)

function boot() {
  const element = document.createElement('div')
  element.id = 'boot'
  element.innerHTML = mark
  document.body.append(element)
  return element
}

describe('launch screen', () => {
  it('carries the thinking mark, the smile and the pieces the dots flow into', () => {
    const element = boot()
    expect(element.querySelectorAll('.dots path')).toHaveLength(3)
    expect(element.querySelectorAll('.smile')).toHaveLength(1)
    // The same pieces as the chat's mark (moods.json), generated by generate_palette.py; a script
    // moves them (brandMerge.ts), not SMIL.
    const pieces = [...element.querySelectorAll('.merge path')]
    expect(pieces).toHaveLength(3)
    expect(element.querySelector('animate')).toBeNull()
    pieces.forEach((piece, index) => {
      expect(piece.getAttribute('d')).toBe(marks.merge[index]!.from)
      expect(piece.getAttribute('data-to')).toBe(marks.merge[index]!.to)
    })
    element.remove()
  })

  it('lets the dots flow into the smile, then fades and leaves', async () => {
    const element = boot()
    const pieces = [...element.querySelectorAll('.merge path')]
    const steps: string[] = []
    const drawn: string[][] = []
    const wait = vi.fn(async (ms: number) => {
      steps.push(`${ms}:${element.className}`)
      drawn.push(pieces.map((piece) => piece.getAttribute('d')!))
    })
    await finishBoot(element, { still: false, wait })
    expect(steps).toEqual([
      `${MERGE_MS}:merging`,
      `${SMILE_MS}:smiling`,
      `${LEAVE_MS}:smiling leaving`,
    ])
    // The flow starts from the dots and ends on the smile's thirds.
    expect(drawn[0]).toEqual(marks.merge.map((piece) => piece.from))
    expect(drawn[1]).toEqual(marks.merge.map((piece) => piece.to))
    expect(element.isConnected).toBe(false)
  })

  it('shows the smile at once with reduced motion', async () => {
    const element = boot()
    const steps: string[] = []
    await finishBoot(element, {
      still: true,
      wait: async (ms) => void steps.push(`${ms}:${element.className}`),
    })
    expect(steps).toEqual([`${SMILE_MS}:smiling`, `${LEAVE_MS}:smiling leaving`])
    expect(element.isConnected).toBe(false)
  })

  it('goes even when a step of its farewell fails', async () => {
    const element = boot()
    const wait = vi.fn(async () => {
      throw new Error('synthetic timer failure')
    })
    await expect(finishBoot(element, { still: false, wait })).rejects.toThrow()
    expect(element.isConnected).toBe(false)
  })

  it('has nothing to end when the page has no launch screen', async () => {
    await expect(finishBoot(null)).resolves.toBeUndefined()
  })

  it('leaves at once in the apps, whose own splash covers the page', async () => {
    const element = boot()
    const wait = vi.fn(async () => undefined)
    await leaveBoot(element, true, { still: false, wait })
    expect(element.isConnected).toBe(false)
    expect(wait).not.toHaveBeenCalled()
  })

  it('plays out in a browser', async () => {
    const element = boot()
    const wait = vi.fn(async () => undefined)
    await leaveBoot(element, false, { still: false, wait })
    expect(wait).toHaveBeenCalledTimes(3)
    expect(element.isConnected).toBe(false)
  })
})
