//! Named Soul activities and source-derived Oudmon core77 candidates.
//! These protocol facts are a fresh inventory, not copied vendor implementation.
//! No candidate is physical RF20 qualification; requested and actual stay distinct.
use crate::codec::core_command;
use serde::{Deserialize, Serialize};

pub const SOURCE_EVIDENCE: &str = "soul-1.0.1214:wx9-a58-ol8-phone-sport";
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct SportPlan {
    pub requested_id: u16,
}
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum SportStatus {
    Start,
    Pause,
    Resume,
    Stop,
}
impl SportStatus {
    pub fn wire(self) -> u8 {
        match self {
            Self::Start => 1,
            Self::Pause => 2,
            Self::Resume => 3,
            Self::Stop => 4,
        }
    }
}
#[derive(Debug, Clone, Serialize)]
pub struct SportCatalogEntry {
    pub requested_id: u16,
    pub resolved_activity_id: u16,
    pub name: &'static str,
    pub family: &'static str,
    pub app_outdoor_gps: bool,
    pub candidate_wire_mode: Option<u8>,
    pub mapping_basis: &'static str,
    pub qualification: &'static str,
    pub evidence_ref: &'static str,
}
#[derive(Debug, Clone, Serialize)]
pub struct SportCapability {
    pub requested_id: u16,
    pub start: bool,
    pub pause: bool,
    pub resume: bool,
    pub stop: bool,
    pub safe_stop_verified: bool,
    pub reason: &'static str,
    pub evidence_ref: Option<&'static str>,
}
#[derive(Debug, Clone, Serialize)]
pub struct SportResult {
    pub requested_id: u16,
    pub candidate_wire_mode: Option<u8>,
    pub actual_wire_mode: Option<u8>,
    pub requested_status: SportStatus,
    pub evidence_ref: Option<&'static str>,
}
impl SportPlan {
    pub fn entry(self) -> Result<&'static SportCatalogEntry, &'static str> {
        SOURCE_CATALOG
            .iter()
            .find(|entry| entry.requested_id == self.requested_id)
            .ok_or("unknown_sport")
    }
}
pub fn source_catalog() -> Vec<SportCatalogEntry> {
    SOURCE_CATALOG.to_vec()
}
/// Pure bounded candidate encoding. It does not accept an HR flag or grant BLE permission.
pub fn candidate_frame(status: SportStatus, plan: SportPlan) -> Result<Vec<u8>, &'static str> {
    let mode = plan
        .entry()?
        .candidate_wire_mode
        .ok_or("source_wire_mapping_unknown")?;
    Ok(core_command(0x77, &[status.wire(), mode])
        .expect("two-byte sport candidate")
        .to_vec())
}
